import { relative, resolve, sep } from 'node:path'
import * as core from '@actions/core'
import {
  buildProject,
  DRAFT_BRANCH_PREFIX,
  type DraftResult,
  draftEntries,
  GitHub,
  GitHubError,
  llmFromEnv,
  loadProject,
} from '@shipdot/cli'

/** Escapes untrusted pull request text for a Markdown table cell, without pinging anyone. */
const cell = (text: string) =>
  text
    .replace(/[\r\n]+/g, ' ')
    .replace(/[\\|]/g, '\\$&')
    .replace(/</g, '&lt;')
    .replace(/@/g, '@​')
    .replace(/`/g, "'")

export function pullBody(result: DraftResult): string {
  const n = result.drafted.length
  const since = result.since
    ? ` since ${result.since.source === 'tag' ? `tag \`${result.since.ref}\`` : result.since.date}`
    : ''
  const rows = result.drafted
    .map((d) => `| #${d.number} ${cell(d.title)} | \`${d.path}\` | ${d.mode} |`)
    .join('\n')
  const skipped = result.skipped.length
    ? `\n<details><summary>Skipped ${result.skipped.length} pull request${result.skipped.length === 1 ? '' : 's'}</summary>\n\n${result.skipped
        .map((s) => `- #${s.number} ${cell(s.title)}: ${cell(s.reason)}`)
        .join('\n')}\n\n</details>\n`
    : ''
  return `## shipdot drafts for review

shipdot drafted **${n}** in-app note${n === 1 ? '' : 's'} from pull requests merged into \`${result.base}\`${since}.

Edit the wording for your users, add a \`target\` to put a hotspot on the new UI, add translations if you need them, then merge. Close this pull request to discard the drafts.

| Pull request | Entry | Mode |
| --- | --- | --- |
${rows}
${skipped}
<!-- Generated by shipdot draft: https://github.com/pipe1os/shipdot -->

### shipdot

skip
`
}

export interface RunOptions {
  env?: Record<string, string | undefined>
  fetch?: typeof fetch
  /** `YYYY-MM-DD` used in the branch name. */
  today?: string
}

/** Entry point of the GitHub Action. Never throws: failures are reported with `core.setFailed`. */
export async function run(options: RunOptions = {}): Promise<void> {
  const env = options.env ?? process.env
  try {
    const token = core.getInput('github-token')
    const llmKey = core.getInput('llm-api-key')
    if (token) core.setSecret(token)
    if (llmKey) core.setSecret(llmKey)

    const workspace = resolve(env.GITHUB_WORKSPACE ?? process.cwd())
    const cwd = resolve(workspace, core.getInput('working-directory') || '.')
    const project = await loadProject(cwd)
    const command = core.getInput('command') || 'draft'

    if (command === 'build') {
      const result = await buildProject(project, { write: true })
      for (const d of result.diagnostics) {
        const file = d.file
          ? relative(workspace, resolve(project.root, d.file)).split(sep).join('/')
          : undefined
        const props = { ...(file && { file }), ...(d.line && { startLine: d.line }) }
        if (d.severity === 'error') core.error(d.message, props)
        else core.warning(d.message, props)
      }
      if (!result.ok) {
        core.setFailed('shipdot build found errors in the entries')
        return
      }
      core.setOutput('entries', result.feed.entries.length)
      core.info(`Built ${result.feed.entries.length} entries: ${result.written.join(', ')}`)
      return
    }
    if (command !== 'draft') {
      core.setFailed(`Unknown command "${command}". Use "draft" or "build".`)
      return
    }

    const repo = env.GITHUB_REPOSITORY
    if (!repo) throw new Error('GITHUB_REPOSITORY is not set')
    const github = new GitHub({
      repo,
      token,
      apiUrl: env.GITHUB_API_URL,
      ...(options.fetch && { fetch: options.fetch }),
    })
    const llm = llmFromEnv(
      {
        SHIPDOT_LLM_PROVIDER: core.getInput('llm-provider') || undefined,
        SHIPDOT_LLM_API_KEY: llmKey || undefined,
        SHIPDOT_LLM_MODEL: core.getInput('llm-model') || undefined,
        SHIPDOT_LLM_BASE_URL: core.getInput('llm-base-url') || undefined,
      },
      project.config.llm,
      core.warning,
      options.fetch,
    )
    const result = await draftEntries({
      project,
      github,
      base: core.getInput('base-branch') || undefined,
      llm,
      log: core.warning,
    })
    core.setOutput('entries', result.drafted.length)
    for (const s of result.skipped) core.info(`Skipped #${s.number}: ${s.reason}`)
    if (!result.files.length) {
      core.info('Nothing to draft.')
      return
    }

    const branch = `${DRAFT_BRANCH_PREFIX}${options.today ?? new Date().toISOString().slice(0, 10)}`
    const existing = await github.openPullFor(branch)
    if (existing) {
      core.notice(`A draft pull request is already open: ${existing.html_url}`)
      core.setOutput('pull-request-url', existing.html_url)
      core.setOutput('pull-request-number', existing.number)
      return
    }
    // Paths in the result are relative to the project; the Git API wants them from the repo root.
    const prefix = relative(workspace, project.root).split(sep).join('/')
    const n = result.drafted.length
    const pull = {
      base: result.base,
      message: 'docs(shipdot): draft in-app release notes',
      files: result.files.map((f) => ({
        path: prefix ? `${prefix}/${f.path}` : f.path,
        content: f.content,
      })),
      title: `shipdot: ${n} draft release note${n === 1 ? '' : 's'} for review`,
      body: pullBody(result),
    }
    let created: { number: number; html_url: string }
    try {
      created = await github.openPullWithFiles({ ...pull, branch })
    } catch (error) {
      // The branch already exists (for example a closed draft from earlier today).
      if (!(error instanceof GitHubError && error.status === 422)) throw error
      created = await github.openPullWithFiles({
        ...pull,
        branch: `${branch}-${Date.now().toString(36)}`,
      })
    }
    core.setOutput('pull-request-url', created.html_url)
    core.setOutput('pull-request-number', created.number)
    core.info(`Opened ${created.html_url}`)
  } catch (error) {
    core.setFailed((error as Error).message)
  }
}
